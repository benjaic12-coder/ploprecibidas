import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {readFileSync,writeFileSync,copyFileSync} from 'node:fs';
await build({configFile:false,plugins:[react()],define:{'process.env.NODE_ENV':JSON.stringify('production')},resolve:{alias:{'@':resolve('.')}},build:{target:'es2020',outDir:'dist-admin-orders',emptyOutDir:true,minify:true,lib:{entry:'cloudflare/admin-orders-client.tsx',name:'PlopManualOrders',formats:['iife'],fileName:()=> 'client.js'}}});
const client=readFileSync('dist-admin-orders/client.js','utf8'),hash=createHash('sha256').update(client).digest('hex');
const assetPath=`/assets/plop-admin-orders-${hash.slice(0,16)}.js`;
writeFileSync('dist-admin-orders/client.txt',client);
copyFileSync('cloudflare/admin-orders.mjs','dist-admin-orders/admin-orders.mjs');
writeFileSync('dist-admin-orders/worker.mjs',`import client from './client.txt';\nimport {handleAdminRequest} from './admin-orders.mjs';\nexport default {fetch(request){return handleAdminRequest(request,{client,assetPath:${JSON.stringify(assetPath)}})}};\n`);
writeFileSync('dist-admin-orders/manifest.json',JSON.stringify({assetPath,sha256:hash,bytes:Buffer.byteLength(client)},null,2));
console.log(JSON.stringify({assetPath,sha256:hash,bytes:Buffer.byteLength(client)}));
