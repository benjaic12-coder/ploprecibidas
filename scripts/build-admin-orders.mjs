import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {readFileSync,writeFileSync,copyFileSync} from 'node:fs';
const runtime=process.argv.includes('--runtime');
await build({configFile:false,plugins:[react()],define:{'process.env.NODE_ENV':JSON.stringify('production')},resolve:{alias:{'@':resolve('.')}},build:{target:'es2020',outDir:'dist-admin-orders',emptyOutDir:true,minify:true,lib:{entry:runtime?'cloudflare/admin-runtime-client.tsx':'cloudflare/admin-orders-client.tsx',name:'PlopManualOrders',formats:['iife'],fileName:()=> 'client.js',cssFileName:'client'}}});
const client=readFileSync('dist-admin-orders/client.js','utf8'),hash=createHash('sha256').update(client).digest('hex');
const assetPath=`/assets/plop-admin-orders-${hash.slice(0,16)}.js`;
const css=runtime?readFileSync('dist-admin-orders/client.css','utf8'):'';
const stylePath=runtime?`/assets/plop-admin-orders-${createHash('sha256').update(css).digest('hex').slice(0,16)}.css`:'';
writeFileSync('dist-admin-orders/client.txt',client);
writeFileSync('dist-admin-orders/style.txt',css);
copyFileSync('cloudflare/admin-orders.mjs','dist-admin-orders/admin-orders.mjs');
writeFileSync('dist-admin-orders/worker.mjs',`import client from './client.txt';\nimport css from './style.txt';\nimport {handleAdminRequest} from './admin-orders.mjs';\nexport default {fetch(request){return handleAdminRequest(request,{client,css,assetPath:${JSON.stringify(assetPath)},stylePath:${JSON.stringify(stylePath)},replaceEntry:${runtime}})}};\n`);
const manifest={assetPath,stylePath,replaceEntry:runtime,sha256:hash,bytes:Buffer.byteLength(client)};
writeFileSync('dist-admin-orders/manifest.json',JSON.stringify(manifest,null,2));
console.log(JSON.stringify(manifest));
